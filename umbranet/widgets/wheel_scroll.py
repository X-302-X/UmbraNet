"""
UmbraNet — прокрутка списков колесом мыши.

Все крупные списки программы (сервисы, «Диспетчер задач», логи, транспорты,
стратегии) рисуются одним paintEvent и обрабатывают колесо сами. Раньше каждый
делал это одинаково грубо:

    self._scroll(-event.angleDelta().y() * 3 // 2)

Одно деление колеса даёт 120 единиц angleDelta, то есть 180 px за щелчок. В
списке сервисов шаг строки — 32 px (service_canvas.ROW_STRIDE), и получалось
5.6 строк за одно движение колеса: «чуть двинул колесо — пронесло пол-списка».

Теперь прокрутка считается в СТРОКАХ списка и потому одинаково ощущается во
всех списках, независимо от их шага строки:

    одно деление колеса = WHEEL_ROWS_PER_NOTCH строк (по умолчанию 2).

Плавные тачпады присылают дробные delta (15, 30, 1…) — масштаб непрерывный,
поэтому мелкое движение прокручивает на пару пикселей, без рывков.

Настройка: чтобы список мотался «чаще» или «реже», достаточно поменять
WHEEL_ROWS_PER_NOTCH (1 — очень плавно, 3 — как в проводнике Windows).
"""

from __future__ import annotations

#: Столько единиц angleDelta даёт одно физическое деление колеса.
WHEEL_UNIT = 120

#: Сколько строк списка прокручивает одно деление колеса.
WHEEL_ROWS_PER_NOTCH = 2


def wheel_delta_px(
    angle_delta_y: int,
    row_stride: int,
    rows_per_notch: int = WHEEL_ROWS_PER_NOTCH,
) -> int:
    """Смещение прокрутки в пикселях для события колеса.

    Знак уже приведён к тому, что ждёт `_scroll()`: колесо от себя (delta > 0)
    прокручивает список вверх (отрицательное смещение).

    `angle_delta_y` — `event.angleDelta().y()`: 120 на обычный щелчок, меньше —
    плавный тачпад. Смещение остаётся пропорциональным, поэтому точные
    устройства прокручивают по чуть-чуть, а не рывками по целой строке.
    """
    if not angle_delta_y or row_stride <= 0 or rows_per_notch <= 0:
        return 0
    return -int(round(angle_delta_y / WHEEL_UNIT * row_stride * rows_per_notch))
